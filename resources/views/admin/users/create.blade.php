<script>
// Role description functionality
const roleSelect = document.getElementById('role');
const roleDescription = document.getElementById('roleDescription');
const roleTitle = document.getElementById('roleTitle');
const roleText = document.getElementById('roleText');

const roleDescriptions = {
    admin: {
        title: 'Administrator',
        text: 'Memiliki akses penuh ke sistem, dapat mengelola semua pengguna, konfigurasi, dan data sistem.'
    },
    student: {
        title: 'Mahasiswa',
        text: 'Dapat mengakses fitur mahasiswa, melihat pembimbing yang ditugaskan, dan mengelola profil pribadi.'
    },
    supervisor: {
        title: 'Pembimbing',
        text: 'Dapat membimbing mahasiswa, melihat daftar mahasiswa yang dibimbing, dan mengelola data pembimbingan.'
    }
};

roleSelect.addEventListener('change', function() {
    const selectedRole = this.value;
    
    if (selectedRole && roleDescriptions[selectedRole]) {
        roleTitle.textContent = roleDescriptions[selectedRole].title;
        roleText.textContent = roleDescriptions[selectedRole].text;
        roleDescription.classList.remove('hidden');
    } else {
        roleDescription.classList.add('hidden');
    }
});

// Auto-focus on first input
document.addEventListener('DOMContentLoaded', function() {
    document.getElementById('email').focus();
});
</script>
